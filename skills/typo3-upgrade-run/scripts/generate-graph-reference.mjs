#!/usr/bin/env node
/**
 * Generate references/graph-nodes.md from the shipped upgrade graph.
 *
 * The YAML is authoritative. This file makes every node contract readable without loading
 * 800 lines of graph definition, and `--check` fails when the two drift apart.
 *
 *   node generate-graph-reference.mjs          write the reference
 *   node generate-graph-reference.mjs --check  exit 1 when it is stale
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const GRAPH = path.resolve(HERE, '../templates/run-directory/config/upgrade-graph.yml');
export const REFERENCE = path.resolve(HERE, '../references/graph-nodes.md');

const STAGES = [
  ['P00', 'P01', 'Intake: identity, data, discovery and inventories (read-only)'],
  ['P02', 'P04', 'Baseline A'],
  ['P05', 'P09', 'Migration ladder'],
  ['P10', 'P10', 'Specialist branches'],
  ['P11', 'P13', 'Final proof and Contract A'],
  ['P14', 'P15', 'Contract B and handover'],
];

const cell = (value) => String(value ?? '—').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function renderGraphReference(definition) {
  const policy = definition.policy ?? {};
  const lines = [
    '# Upgrade graph nodes',
    '',
    '<!-- Generated by scripts/generate-graph-reference.mjs from templates/run-directory/config/upgrade-graph.yml. Do not edit by hand. -->',
    '',
    'The YAML graph is authoritative. Each row is the contract `t3u node-brief --node <id>` hands to a worker:',
    'what to achieve, when it is done, and where its evidence goes. Flags: **R** independent review required,',
    '**M** measurement node (may recalibrate config with an ADR), **A** approval required, **L** green evidence loop required.',
    '',
    `Policy: ${Object.entries(policy).map(([k, v]) => `\`${k}: ${typeof v === 'object' ? JSON.stringify(v) : v}\``).join(', ')}.`,
    `Nodes: ${Object.keys(definition.nodes).length}; edges: ${definition.edges.length}; bounded retry edges: ${definition.edges.filter((e) => e.retry === true).length}.`,
  ];
  const phaseNumber = (node) => Number(String(node.phase ?? '').slice(1));
  for (const [from, to, title] of STAGES) {
    const low = Number(from.slice(1)), high = Number(to.slice(1));
    const rows = Object.entries(definition.nodes).filter(([, node]) => phaseNumber(node) >= low && phaseNumber(node) <= high);
    if (!rows.length) continue;
    lines.push('', `## ${title}`, '', '| Node | Phase | Owner | Mutation | Flags | Objective | Done when | Evidence |', '|---|---|---|---|---|---|---|---|');
    for (const [id, node] of rows) {
      const flags = [node.review === 'required' && 'R', node.measurement && 'M', node.approval === 'required' && 'A',
        node.evidence_loop === 'required' && 'L'].filter(Boolean).join(' ') || '—';
      lines.push(`| \`${id}\` | ${node.phase} | ${cell(node.skill ?? 'controller')} | ${node.mutation ?? 'none'} | ${flags} | ${cell(node.objective)} | ${cell(node.done)} | \`${cell(node.evidence)}\` |`);
    }
  }
  return `${lines.join('\n')}\n`;
}

async function main(argv) {
  const definition = parseYaml(await readFile(GRAPH, 'utf8'));
  const next = renderGraphReference(definition);
  if (argv.includes('--check')) {
    const current = await readFile(REFERENCE, 'utf8').catch(() => '');
    if (current !== next) {
      process.stderr.write('references/graph-nodes.md is stale. Run: node scripts/generate-graph-reference.mjs\n');
      return 1;
    }
    return 0;
  }
  await writeFile(REFERENCE, next, 'utf8');
  process.stdout.write(`Wrote ${path.relative(process.cwd(), REFERENCE)}\n`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = await main(process.argv.slice(2));
}
